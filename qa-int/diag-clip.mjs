import { chromium } from "playwright";
import { launchGL } from "../tools/gl-launch.mjs";
import { sleep, waitIdle } from "./h.mjs";
import { resolve } from "node:path";
const BASE = process.argv[2] ?? "http://localhost:4184";
const browser = await launchGL(chromium);
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
await page.goto(BASE + "/?step=18", { waitUntil: "load" });
await page.waitForFunction(() => !!window.__wp1 && !document.querySelector("#boot"));
await waitIdle(page);
const sb = await page.locator("#stage-wrap").boundingBox();
const cv = await page.locator("canvas.lv-canvas").first().boundingBox();
const cvAll = await page.locator("canvas.lv-canvas").count();
const reader = await page.locator("#reader").boundingBox();
console.log(JSON.stringify({ sb, cv, cvAll, reader }, null, 1));
const clip = { x: Math.round(cv.x + cv.width * 0.42), y: Math.round(cv.y + cv.height * 0.16), width: Math.round(cv.width * 0.46), height: Math.round(cv.height * 0.44) };
console.log("clip:", JSON.stringify(clip));
await page.screenshot({ path: resolve("qa-int/shots/diag-dark-crop2.png"), clip });
await browser.close();
